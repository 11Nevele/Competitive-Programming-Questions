vector<int> ans;
void dfs(int x, int pre)
{
    if (x == 0)
    {
        for (int i = 0; i < ans.size() - 1; i++)
        {
            cout << ans[i] << " ";
        }
        cout << ans.back() << endl;
        return;
    }
    for (int i = min(pre, x); i > 0; --i)
    {
        ans.push_back(i);
        dfs(x - i, i);
        ans.pop_back();
    }
}

