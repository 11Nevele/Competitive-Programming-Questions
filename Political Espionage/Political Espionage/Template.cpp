inline int read() {
    int ret = 0, f = 1; char ch = getchar();
    while (ch < '0' || ch>'9') { if (ch == '-') f = -f; ch = getchar(); }
    while (ch >= '0' && ch <= '9') ret = ret * 10 + ch - '0', ch = getchar();
    return ret * f;
}
inline long long readLL()
{
    long long ret = 0, f = 1; char ch = getchar();
    while (ch < '0' || ch>'9') { if (ch == '-') f = -f; ch = getchar(); }
    while (ch >= '0' && ch <= '9') ret = ret * 10 + ch - '0', ch = getchar();
    return ret * f;
}
inline void write(int x)
{
    if (x < 0)
        putchar('-'), x = -x;
    if (x > 9)
        write(x / 10);
    putchar(x % 10 + '0');
    return;
}
inline void write(long long x)
{
    if (x < 0)
        putchar('-'), x = -x;
    if (x > 9)
        write(x / 10);
    putchar(x % 10 + '0');
    return;
}

int main()
{
    int n = read();
    vector<LL> arr(n, 1);
    arr[0] = 10000000000;
	for (int i = 1; i < n; i++)
	{
        LL mx = ceil((double)arr[i - 1] / 2) - 1;
        LL cur = mx / 2 + 1;
        if (cur + n - i - 1 >= mx)
        {
            arr[i] = mx - (n - i - 1) - 1;
            break;
        }
        else
            arr[i] = cur;
	}
    for(LL i : arr)
		write(i), putchar(' ');
    putchar('\n');
    return 0;
}